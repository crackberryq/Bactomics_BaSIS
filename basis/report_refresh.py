"""Refresh an audited optional-module report without executing analyses.

Native records, candidate analyses, selection and interpretation are immutable.
Only source-backed candidate labels and newly rendered report views change.
"""
from __future__ import annotations

from copy import deepcopy
from datetime import datetime, timezone
import json
import hashlib
from pathlib import Path

from .candidate_labels import refresh_candidate_labels
from .util import atomic_json, hash_object, sha256_file


LABEL_FIELDS = frozenset({"gene", "family", "source_gene_labels", "label_provenance"})
CACHE_FIELDS = frozenset({"cache_key", "cache_hit", "cache_checked_at", "deep_cache"})


def protected_candidates(candidates):
    """Hash every candidate field except the four allowed display-label fields."""
    return hash_object([{k: v for k, v in c.items() if k not in LABEL_FIELDS}
                        for c in candidates])


def verify_source(evidence):
    """Check the embedded reconciliation seals, not remote native file paths."""
    if evidence.get("schema_version") != "basis-report-1":
        raise ValueError("Expected a basis-report-1 evidence bundle")
    for key in ("samples", "records", "deep_records"):
        if not isinstance(evidence.get(key), list):
            raise ValueError(f"Missing or invalid {key}")
    run = evidence.get("run") or {}
    if run.get("report_refresh"):
        raise ValueError("Use the original reconciled evidence, not a previous reporting refresh")
    review = run.get("report_reconciliation") or {}
    if review.get("schema_version") != "basis-ice-reconciliation-1":
        raise ValueError("Expected the saved update-27 ICEscreen reconciliation bundle")
    sid = review.get("sample_id")
    ice = [r for r in evidence["records"]
           if r.get("sample_id") == sid and r.get("module") == "icescreen"]
    if (len(ice) != 1 or ice[0].get("execution_status") != "completed"
            or hash_object(ice[0]) != review.get("retry_record_sha256")):
        raise ValueError("Reconciled ICEscreen record differs from its embedded audit seal")
    changes = review.get("deep_changes") or []
    if not evidence["deep_records"] or len(changes) != len(evidence["deep_records"]):
        raise ValueError("Expected an audit seal for every DeepSafe record")
    seen = set()
    for deep in evidence["deep_records"]:
        sample = deep.get("sample_id")
        matching = [c for c in changes if c.get("sample_id") == sample]
        if sample in seen or len(matching) != 1:
            raise ValueError("Ambiguous DeepSafe reconciliation seals")
        seen.add(sample)
        if (deep.get("execution_status") != "completed"
                or not isinstance(deep.get("candidates"), list)
                or hash_object(deep["candidates"]) != matching[0].get("candidate_evidence_sha256")):
            raise ValueError(f"DeepSafe candidate evidence differs from its embedded audit seal: {sample}")


def prepare_refresh(evidence, source_path, source_hash, generated_at):
    """Return a reporting copy and preserve the original reconciliation audit."""
    verify_source(evidence)
    # Derived findings and recommendations are regenerated by the renderer.
    merged = {key: deepcopy(evidence[key])
              for key in ("run", "samples", "records", "deep_records")}
    audit = {
        "schema_version": "basis-report-refresh-1",
        "source_evidence": {"path": str(source_path), "sha256": source_hash},
        "source_run_id": evidence["run"].get("run_id"),
        "report_generated_at_utc": generated_at,
        "native_analyses_run": False, "gpu_inference_run": False,
        "verification_scope": "Embedded source reconciliation seals and source-file integrity; native artifacts are not reverified.",
        "historical_audit_scope": "Existing reconciliation hashes describe the original source snapshot. This refresh records separate before/after metadata hashes.",
        "canonical_label_corrections": 0, "candidate_metadata_updates": 0,
        "deep_changes": [],
        "native_records_sha256": hash_object(evidence["records"]),
        "samples_sha256": hash_object(evidence["samples"]),
    }
    for old, deep in zip(evidence["deep_records"], merged["deep_records"]):
        changes = []
        for index, candidate in enumerate(deep["candidates"]):
            if not candidate.get("selected"):
                continue
            updated, change = refresh_candidate_labels(candidate)
            if change["changed_fields"]:
                changes.append(change)
                deep["candidates"][index] = updated
                audit["candidate_metadata_updates"] += 1
                if {"gene", "family"}.intersection(change["changed_fields"]):
                    audit["canonical_label_corrections"] += 1
        before_protected = protected_candidates(old["candidates"])
        if protected_candidates(deep["candidates"]) != before_protected:
            raise RuntimeError("Candidate analyses, selection or interpretation changed")
        removed_cache = {k: deep.pop(k) for k in CACHE_FIELDS if changes and k in deep}
        record_metadata = lambda r: {k: v for k, v in r.items()
                                     if k != "candidates" and k not in CACHE_FIELDS}
        if record_metadata(old) != record_metadata(deep):
            raise RuntimeError("DeepSafe execution metadata changed")
        audit["deep_changes"].append({
            "sample_id": deep.get("sample_id"), "candidate_label_changes": changes,
            "record_before_sha256": hash_object(old), "record_after_sha256": hash_object(deep),
            "candidates_before_sha256": hash_object(old["candidates"]),
            "candidates_after_sha256": hash_object(deep["candidates"]),
            "protected_candidate_fields_sha256": before_protected,
            "analyses_selection_interpretation_unchanged": True,
            "removed_cache_metadata": removed_cache,
        })
    if hash_object(merged["records"]) != audit["native_records_sha256"]:
        raise RuntimeError("Native records changed during reporting refresh")
    merged["run"]["report_refresh"] = audit
    return merged


def refresh_report(source, outdir):
    """Write a fresh bundle, seal its outputs and leave the source untouched."""
    from .report import write_report

    source, outdir = Path(source).resolve(), Path(outdir).resolve()
    if outdir.exists():
        raise FileExistsError(f"Output already exists; choose a new directory: {outdir}")
    source_hash = sha256_file(source)
    print("Checking saved reconciliation and candidate evidence seals...", flush=True)
    evidence = json.loads(source.read_text(encoding="utf-8"))
    generated_at = datetime.now(timezone.utc).isoformat()
    merged = prepare_refresh(evidence, source, source_hash, generated_at)
    audit = deepcopy(merged["run"]["report_refresh"])
    before_render = hash_object(merged)
    outdir.mkdir(parents=True, exist_ok=False)
    print("Rendering reporting corrections; no native analyses or GPU inference...", flush=True)
    artifacts = write_report(merged["run"], merged["samples"], merged["records"],
                             merged["deep_records"], outdir)
    if hash_object(merged) != before_render:
        raise RuntimeError("Renderer changed input evidence; refresh not finalized")
    if sha256_file(source) != source_hash:
        raise RuntimeError("Source evidence changed during rendering; refresh not finalized")
    code_files = set(Path(__file__).parent.glob("report*.py")) | {
        Path(__file__).parent / "candidate_labels.py"}
    audit.update(source_unchanged=True, artifacts=artifacts,
                 report_finished_at_utc=datetime.now(timezone.utc).isoformat(),
                 renderer_source_sha256={p.name: sha256_file(p) for p in sorted(code_files)},
                 output_file_sha256={str(p.relative_to(outdir)): sha256_file(p)
                                     for p in sorted(outdir.rglob("*")) if p.is_file()})
    atomic_json(outdir / "review.json", audit)
    return merged, artifacts


def refresh_saved_report(source, outdir, artifact_roots=None, expected_sha256=None):
    """Re-render any saved basis-report-1 bundle without modifying its evidence.

    This general installed-package entry point deliberately does not perform the
    historical update-27 label corrections in ``refresh_report`` above. Saved
    source evidence is hashed, not independently revalidated. Tree/plot exporters
    retain their own artifact checks. Absolute native paths remain tied to the
    original saved run; use ``basis control-panel`` to browse those artifacts.
    """
    from . import __version__
    from .report import write_report

    from .report_artifacts import allowed_roots, build_index, write_index

    source = Path(source).expanduser().resolve(strict=True)
    output_path = Path(outdir).expanduser()
    if output_path.is_symlink():
        raise FileExistsError(f"Output already exists as a symlink: {output_path}")
    outdir = output_path.resolve()
    if not source.is_file():
        raise ValueError(f"Evidence is not a file: {source}")
    if outdir.exists():
        raise FileExistsError(f"Output already exists; choose a new directory: {outdir}")
    if outdir.is_relative_to(source.parent) or source.parent.is_relative_to(outdir):
        raise ValueError("Output must be outside the source report directory and its ancestors")
    raw = source.read_bytes()
    source_hash = hashlib.sha256(raw).hexdigest()
    if expected_sha256 is not None:
        if (not isinstance(expected_sha256, str) or len(expected_sha256) != 64
                or any(c not in "0123456789abcdef" for c in expected_sha256.lower())):
            raise ValueError("Expected evidence SHA256 must contain 64 hexadecimal characters")
        if source_hash != expected_sha256.lower():
            raise ValueError("Evidence SHA256 differs from the expected saved snapshot")
    evidence = json.loads(raw)
    if not isinstance(evidence, dict) or evidence.get("schema_version") != "basis-report-1":
        raise ValueError("Expected a basis-report-1 evidence bundle")
    if not isinstance(evidence.get("run"), dict):
        raise ValueError("Missing or invalid run object")
    for key in ("samples", "records", "deep_records"):
        if not isinstance(evidence.get(key), list) or any(not isinstance(v, dict) for v in evidence[key]):
            raise ValueError(f"Missing or invalid {key}")
    for record in evidence["deep_records"]:
        if not isinstance(record.get("candidates", []), list) or any(
                not isinstance(v, dict) for v in record.get("candidates", [])):
            raise ValueError("Invalid candidate inventory")
    replays = evidence["run"].get("report_replays", [])
    if not isinstance(replays, list) or any(not isinstance(v, dict) for v in replays):
        raise ValueError("Invalid reporting history")
    roots = allowed_roots(source.parent, artifact_roots)
    source_index = build_index(evidence, source, source_hash, outdir, roots)
    merged = {key: deepcopy(evidence[key]) for key in ("run", "samples", "records", "deep_records")}
    audit = {
        "schema_version": "basis-report-replay-1", "renderer_version": __version__,
        "source_evidence": {"path": str(source), "sha256": source_hash},
        "source_run_id": evidence["run"].get("run_id"),
        "report_generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "native_analyses_run": False, "gpu_inference_run": False,
        "interpretations_unchanged": True,
        "verification_scope": "Source-file integrity and immutable saved records; native artifacts, resources and scientific conclusions are not independently revalidated.",
        "recorded_evidence_sha256": {key: hash_object(evidence[key])
                                    for key in ("samples", "records", "deep_records")},
        "expected_source_sha256": expected_sha256,
        "linked_artifact_scope": "Exact declared artifacts and original report within explicitly authorized roots; directories are not recursively scanned. Contents are not independently revalidated.",
        "artifact_roots": [str(root) for root in roots],
    }
    merged["run"]["report_replays"] = [*deepcopy(replays), deepcopy(audit)]
    before_render = hash_object(merged)
    outdir.mkdir(parents=True, exist_ok=False)
    print("Rendering saved evidence; no native analyses or GPU inference...", flush=True)
    atomic_json(outdir / "replay-status.json", {"finalized": False, "source_evidence": audit["source_evidence"]})
    source_artifacts = write_index(source_index, outdir)
    artifacts = write_report(merged["run"], merged["samples"], merged["records"], merged["deep_records"], outdir)
    if hash_object(merged) != before_render:
        raise RuntimeError("Renderer changed input evidence; replay not finalized")
    if sha256_file(source) != source_hash:
        raise RuntimeError("Source evidence changed during rendering; replay not finalized")
    for key in ("samples", "records", "deep_records"):
        if hash_object(merged[key]) != audit["recorded_evidence_sha256"][key]:
            raise RuntimeError(f"Saved {key} changed; replay not finalized")
    source_index["evidence_sha256"] = sha256_file(outdir / "evidence.json")
    # Refresh availability immediately before sealing the view. This does not
    # inspect arbitrary descendants or validate native scientific content.
    latest_index = build_index(evidence, source, source_hash, outdir, roots)
    source_index.update(entries=latest_index["entries"], counts=latest_index["counts"])
    source_artifacts = write_index(source_index, outdir)
    artifacts = {**artifacts, **source_artifacts}
    if sha256_file(source) != source_hash:
        raise RuntimeError("Source evidence changed during artifact indexing; replay not finalized")
    code_files = set(Path(__file__).parent.glob("report*.py"))
    audit.update(source_unchanged=True, finalized=True, artifacts=artifacts,
                 report_finished_at_utc=datetime.now(timezone.utc).isoformat(),
                 renderer_source_sha256={p.name: sha256_file(p) for p in sorted(code_files)},
                 output_file_sha256={str(p.relative_to(outdir)): sha256_file(p)
                                     for p in sorted(outdir.rglob("*"))
                                     if p.is_file() and p.name != "replay-status.json"})
    atomic_json(outdir / "replay-audit.json", audit)
    atomic_json(outdir / "replay-status.json", {"finalized": True, "audit": "replay-audit.json",
                                               "source_evidence": audit["source_evidence"]})
    artifacts = {**artifacts, "replay_audit": str(outdir / "replay-audit.json")}
    print("Report:", artifacts["html"], flush=True)
    return merged, artifacts
