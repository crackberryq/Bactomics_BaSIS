"""Freeze verified rc2 resources in a new retry configuration.

This narrow migration does not declare old native analyses reusable. It imports
only completed, checksum-verified resource snapshots from audited rc2 provider
implementations; failed staging directories are never candidates.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
import re

import yaml

from .bootstrap import MANIFEST, POLICY, _load_receipt, receipt_path, verify_snapshot
from .config import PATH_KEYS, load_config
from .util import hash_object, now, read_json, sha256_file
from .workflow_runtime import read_document

# These provider branches have no resource-format changes in the rc3 repair.
# Pin the audited rc2 implementation rather than trusting an arbitrary old
# manifest merely because it calls itself a compatible version.
AUDITED_PROVIDER_SOURCE = "25b3c3e0305641caa5db071e8cb30785bddd5339d88e794ad8257c7cc640db9e"
RECOVERABLE = {
    "amrfinder": "amrfinder", "card": "rgi", "genomad": "genomad",
    "mobsuite": "mobsuite", "bacmet": "bacmet", "isescan": "isescan",
    "icescreen": "icescreen",
}
UPDATE_FIELDS = {"database", "database_version", "metadata", "reference_fasta"}


def _unresolved_config(config):
    """Ignore only fields generated by the documented automatic device probe."""
    result = copy.deepcopy(config)
    execution = result["execution"]
    if execution.get("device") in {"auto", "cpu", "cuda"}:
        execution.pop("device_resolution", None)
        execution["gpus"] = 0
        result["modules"]["pathogenfinder2"].pop("device_policy", None)
        result["modules"]["pathogenfinder2"]["gpus"] = 0
    return result


def _saved_run(config, run_id=None):
    outdir = Path(config["outdir"])
    if run_id is None:
        run_id = read_json(outdir / "run.json").get("run_id")
    if not isinstance(run_id, str) or not re.fullmatch(r"[A-Za-z0-9_.+-]+", run_id):
        raise ValueError("A valid saved run identifier is required")
    root = outdir / "provenance" / "scheduler" / run_id
    context = read_document(root / "run-context.json")
    if context.get("run_id") != run_id or context.get("scheduler_receipt_dir") != str(root):
        raise ValueError("Saved run context path or run identity mismatch")
    if context.get("version") != "0.3.0rc2":
        raise ValueError("Resource recovery supports the audited 0.3.0rc2 run format only")
    candidates = []
    for path in sorted((outdir / "provenance" / "plans").glob("*.json")):
        plan = read_json(path)
        if (plan.get("source_hash") != context.get("source_hash")
                or hash_object(plan.get("config")) != context.get("config_hash")):
            continue
        content = {k: v for k, v in plan.items() if k not in {"plan_hash", "plan_path"}}
        if hash_object(content) != plan.get("plan_hash") or path.stem != plan.get("plan_hash"):
            raise ValueError("Saved execution plan checksum mismatch")
        if (plan.get("version") != "0.3.0rc2" or plan.get("schema_version") != 1
                or plan.get("outdir") != str(outdir)
                or plan.get("options") != context.get("options")):
            raise ValueError("Saved execution plan does not match run context")
        if _unresolved_config(plan["config"]) != _unresolved_config(config):
            raise ValueError("Current configuration differs from the saved run; use its original configuration")
        candidates.append((path, plan))
    if len(candidates) != 1:
        raise ValueError("Expected exactly one verified execution plan for the saved run")
    return root, context, *candidates[0]


def _check_spec(spec):
    from .workflow_environments import environment_for_recipe
    if (spec.get("provider") != spec.get("id")
            or spec.get("provider_source_sha256") != AUDITED_PROVIDER_SOURCE
            or spec.get("dependencies") or spec.get("options")
            or spec.get("packaged_inputs_sha256")):
        raise ValueError("Resource specification is outside the audited rc2 recovery scope: " + spec["id"])
    if sha256_file(environment_for_recipe(spec["recipe"])) != spec.get("recipe_sha256"):
        raise ValueError("Environment recipe changed; prepare this resource with the new release: " + spec["id"])
    runtime = ({k: spec[k] for k in ("command_prefix", "environment_backend", "environment_storage")}
               if spec["id"] in {"isescan", "icescreen"} else {})
    key = hash_object({"policy": POLICY, "provider": spec["id"],
        "provider_source_sha256": spec["provider_source_sha256"],
        "recipe_sha256": spec["recipe_sha256"], "options": spec["options"],
        "preset": spec["preset"], "runtime_binding": runtime,
        "packaged_inputs_sha256": spec["packaged_inputs_sha256"], "dependencies": {}})
    expected = Path(spec["cache_directory"]) / "snapshots" / spec["id"] / key
    if spec.get("cache_key") != key or spec.get("snapshot") != str(expected):
        raise ValueError("Resource specification cache identity mismatch: " + spec["id"])


def prepare_recovery(config_path, output_config, *, output_directory=None, run_id=None, vfdb_snapshot=None):
    """Verify resources and write a new config plus audit; perform no downloads."""
    config_path = Path(config_path).resolve(strict=True)
    output_config = Path(output_config).resolve()
    audit_path = output_config.with_suffix(".resource-recovery.json")
    if config_path == output_config or output_config.exists() or audit_path.exists():
        raise ValueError("Retry configuration and audit must be new files")
    config = load_config(config_path)
    config_hash = sha256_file(config_path)
    root, context, plan_path, plan = _saved_run(config, run_id)
    result = copy.deepcopy(config)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    outdir = Path(output_directory).expanduser().resolve() if output_directory else Path(
        config["outdir"] + "-retry-" + stamp)
    if outdir.exists() or outdir == Path(config["outdir"]):
        raise ValueError("Retry output directory must be new; original results are preserved")
    if config.get("resources", {}).get("policy") != "auto":
        raise ValueError("Recovery expects the original automatic-resource configuration")
    recovered, retained = [], []
    seen = set()
    for spec in plan.get("bootstrap_resources", []):
        name = spec["id"]
        if name in seen:
            raise ValueError("Duplicate resource identifier in saved plan: " + name)
        seen.add(name)
        if name not in RECOVERABLE:
            retained.append({"resource_id": name, "action": "automatic_preparation",
                             "reason": "not_in_audited_recovery_scope"})
            continue
        path = receipt_path(root, name)
        if not path.is_file():
            retained.append({"resource_id": name, "action": "automatic_preparation", "reason": "no_receipt"})
            continue
        receipt = read_document(path)
        expected = {"schema": "basis-bootstrap-receipt-v1", "run_id": root.name,
                    "plan_hash": plan["plan_hash"], "source_hash": plan["source_hash"],
                    "resource_id": name, "cache_key": spec["cache_key"]}
        if any(receipt.get(key) != value for key, value in expected.items()):
            raise ValueError("Resource receipt identity mismatch: " + name)
        if receipt.get("status") != "ready":
            retained.append({"resource_id": name, "action": "automatic_preparation", "reason": "preparation_not_ready"})
            continue
        _check_spec(spec)
        receipt, recorded_manifest = _load_receipt(plan, root, spec)
        manifest = verify_snapshot(spec)
        if (manifest != recorded_manifest or manifest.get("spec") != spec
                or manifest.get("provider") != name):
            raise ValueError("Verified resource does not match its original specification: " + name)
        module = RECOVERABLE[name]
        prepared = manifest["result"]
        updates = prepared.get("module_updates", {})
        if set(updates) != {module} or prepared.get("deep_updates"):
            raise ValueError("Unexpected recovered resource target: " + name)
        values = updates[module]
        if not isinstance(values, dict) or set(values) - UPDATE_FIELDS or not values.get("database"):
            raise ValueError("Unexpected recovered resource configuration fields: " + name)
        section = result["modules"][module]
        for key, value in values.items():
            if key in PATH_KEYS and (not isinstance(value, str) or not Path(value).is_absolute()):
                raise ValueError("Recovered resource paths must be absolute: " + name)
            if section.get(key) not in (None, "") and section[key] != value:
                raise ValueError("Recovery would replace an explicit resource field: " + module + "." + key)
            section[key] = copy.deepcopy(value)
        identity = {"resource_id": name, "cache_key": spec["cache_key"],
                    "manifest": str(Path(spec["snapshot"]) / MANIFEST),
                    "manifest_sha256": receipt["manifest_sha256"],
                    "recovered_from_run": context["run_id"], "original_source_hash": plan["source_hash"],
                    "original_provider_source_sha256": spec["provider_source_sha256"]}
        section.setdefault("resource_bootstrap", []).append(identity)
        recovered.append({**identity, "module": module, "receipt": str(path),
                          "receipt_sha256": sha256_file(path), "snapshot": spec["snapshot"],
                          "file_count": len(manifest["files"]), "external_file_count": len(manifest["external_files"]),
                          "module_updates": values, "original_specification": spec})
    legacy_vfdb = None
    if vfdb_snapshot is not None:
        from .vfdb_recovery import verify_legacy_vfdb_snapshot
        values, legacy_vfdb = verify_legacy_vfdb_snapshot(vfdb_snapshot)
        if not isinstance(values, dict) or set(values) - (UPDATE_FIELDS | {"database_manifest"}) or not values.get("database"):
            raise ValueError("Unexpected legacy VFDB resource fields")
        section = result["modules"]["vfdb"]
        for key, value in values.items():
            if key in PATH_KEYS and (not isinstance(value, str) or not Path(value).is_absolute()):
                raise ValueError("Recovered VFDB resource paths must be absolute")
            if section.get(key) not in (None, "") and section[key] != value:
                raise ValueError("Recovery would replace an explicit VFDB resource field: " + key)
            section[key] = copy.deepcopy(value)
        section["resource_recovery"] = {"audit": str(audit_path), "kind": "verified_legacy_vfdb"}
        retained = [row for row in retained if row["resource_id"] != "vfdb"]
    if not recovered and legacy_vfdb is None:
        raise ValueError("No completed resource snapshots qualified for audited recovery")
    result.pop("config_path", None)
    result["outdir"] = str(outdir)
    audit = {"schema": "basis-resource-recovery-v1", "created_at": now(),
             "source_version": "0.3.0rc2", "source_config": str(config_path),
             "source_config_sha256": config_hash, "source_run": context["run_id"],
             "source_run_context": str(root / "run-context.json"),
             "source_run_context_sha256": sha256_file(root / "run-context.json"),
             "source_plan": str(plan_path), "source_plan_sha256": sha256_file(plan_path),
             "source_plan_hash": plan["plan_hash"], "source_hash": plan["source_hash"],
             "recovered": recovered, "legacy_vfdb": legacy_vfdb, "retained_automatic": retained,
             "native_analyses_reused": False, "downloads_performed": False,
             "input_sequences_revalidated": False, "original_files_changed": False,
             "scope": "Verified frozen resources only; the next run validates inputs and performs current-release analyses.",
             "output_config": str(output_config), "output_directory": str(outdir)}
    result["resource_recovery"] = {"audit": str(audit_path), "source_run": context["run_id"],
                                   "recovered_resources": [r["resource_id"] for r in recovered]}
    yaml_text = yaml.safe_dump(result, sort_keys=False)
    audit["output_config_sha256"] = hashlib.sha256(yaml_text.encode("utf-8")).hexdigest()
    audit["content_sha256"] = hash_object(audit)
    if sha256_file(config_path) != config_hash:
        raise ValueError("Source configuration changed during resource verification")
    output_config.parent.mkdir(parents=True, exist_ok=True)
    with audit_path.open("x", encoding="utf-8") as handle:
        json.dump(audit, handle, indent=2, sort_keys=True, allow_nan=False)
        handle.write("\n")
    try:
        with output_config.open("x", encoding="utf-8") as handle:
            handle.write(yaml_text)
    except Exception:
        audit_path.unlink()
        raise
    return audit


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-c", "--config", required=True, help="Original rc2 configuration")
    parser.add_argument("--out-config", required=True, help="New retry configuration; never overwritten")
    parser.add_argument("--outdir", help="New result directory (default: timestamped sibling of original)")
    parser.add_argument("--run-id", help="Saved rc2 run ID (default: run.json)")
    parser.add_argument("--vfdb-snapshot", help="Explicit legacy VFDB directory with its verified provenance.json")
    args = parser.parse_args(argv)
    from .progress import verbosity
    with verbosity(True):
        audit = prepare_recovery(args.config, args.out_config, output_directory=args.outdir,
                                 run_id=args.run_id, vfdb_snapshot=args.vfdb_snapshot)
    print("Verified resources:", ", ".join(row["resource_id"] for row in audit["recovered"]))
    if audit["legacy_vfdb"] is not None:
        print("Legacy VFDB: checksum-verified frozen snapshot")
    print("Retry config:", audit["output_config"])
    print("Audit:", str(Path(audit["output_config"]).with_suffix(".resource-recovery.json")))
    print("New results:", audit["output_directory"])
    print("Original resources/results preserved. No downloads or native analyses run.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
